const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const {_electron}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const {isolateWindow,prepareProfile}=require('./acceptance-window.cjs');
const exe=process.env.ANNOTATION_EXE;
const root=process.env.ANNOTATION_EVIDENCE||'D:/Artifacts/AnnotationCapture/acceptance/packaged';
fs.mkdirSync(root,{recursive:true});
let app;
(async()=>{
    assert.ok(exe,'ANNOTATION_EXE is required');
    prepareProfile(path.join(path.dirname(exe),'AnnotationCapture-data'));
    app=await _electron.launch({executablePath:exe,cwd:path.dirname(exe),args:['--testMode'],env:{...process.env,PATH:`${process.env.SystemRoot}/System32;${process.env.SystemRoot}`,NODE_PATH:'',NODE_OPTIONS:'',DEEPSEEK_API_KEY:'',ANNOTATION_DEEPSEEK_API_KEY:'',ANNOTATION_DATA_DIR:''},timeout:30000});
    const page=await app.firstWindow();await page.waitForSelector('#ac-start');
    await isolateWindow(app,page);
    const initial=await page.evaluate(()=>require('electron').ipcRenderer.invoke('annotation:state'));
    const data=await app.evaluate(({app})=>app.getPath('userData'));
    assert.equal(path.resolve(data),path.resolve(path.dirname(exe),'AnnotationCapture-data'));
    assert.equal(initial.login.loggedIn,false);
    assert.equal(await page.locator('#ac-api-key').count(),0);
    assert.deepEqual(Object.keys(initial.config).sort(),['archiveRoot','fullShortcut','ocrShortcut','outputFormat','penColor','penWidth','shortcut','showMagnifier','version']);
    assert.equal(initial.config.penColor,'#ff0000');
    assert.equal(initial.config.showMagnifier,false);
    assert.equal(await page.locator('#ac-invite-code').getAttribute('type'),'password');
    await page.locator('#ac-save-settings').click();await page.waitForFunction(()=>document.querySelector('#ac-panel-status').textContent.includes('设置已保存'));
    const registered=await app.evaluate(({globalShortcut},keys)=>keys.every(key=>globalShortcut.isRegistered(key)),[initial.config.shortcut,initial.config.fullShortcut,initial.config.ocrShortcut]);assert.ok(registered);
    await page.screenshot({path:path.join(root,'fresh-portable-settings.png')});
    fs.writeFileSync(path.join(root,'portable-report.json'),JSON.stringify({passed:true,exe,data,requiresDeveloperRuntime:false,processPath:'Windows system directories only',noClientAPIConfiguration:true,invitationRequired:true,bothGlobalShortcutsRegistered:true},null,2));
    console.log('PORTABLE_FRESH_PROFILE_PASSED');
})().catch(e=>{console.error(e);process.exitCode=1;}).finally(async()=>{if(app)await app.evaluate(({app})=>app.exit());});
